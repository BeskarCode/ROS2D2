"""The firmware as a Wokwi project (README.md): r2_pico_sensors.h (the sketch and its headers in
one file), sketch.ino (that file, built with WOKWI; in a header, so the Arduino builder adds no
prototypes ahead of its types), diagram.json (the carrier board's parts) and libraries.txt.
    python make.py
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SKETCH = HERE.parent

# The carrier board's wiring (Board.h): connector, its GPIO(s), its status LED
VL = [("VL1", 2, 28), ("VL2", 3, 27), ("VL3", 4, 22), ("VL4", 5, 9)]
US = [("US1", 10, 0), ("US2", 12, 1), ("US3", 14, 6), ("US4", 18, 7), ("US5", 20, 8)]


def inline(path, seen, out):
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r'#include "(.+)"', line)
        if m:
            name = m.group(1)
            if name not in seen:
                seen.add(name)
                inline(SKETCH / name, seen, out)
        elif line.strip() != "#pragma once":
            out.append(line)


GENERATED = "// Generated by wokwi/make.py from r2_pico_sensors.ino and its headers: edit those, not this."


def sketch():
    out = [GENERATED, "#pragma once"]
    inline(SKETCH / "r2_pico_sensors.ino", set(), out)
    return "\n".join(out) + "\n"


def diagram():
    parts = [
        {"type": "board-pi-pico-2", "id": "pico", "top": 0, "left": 0, "attrs": {"env": "arduino-community"}},
        {"type": "board-ssd1306", "id": "oled", "top": -120, "left": 200, "attrs": {"i2cAddress": "0x3c"}},
        {"type": "wokwi-pushbutton", "id": "btn", "top": -110, "left": 360, "attrs": {"color": "blue", "label": "display"}},
    ]
    wires = [
        ["oled:GND", "pico:GND.8", "black", []],
        ["oled:VCC", "pico:3V3", "red", []],
        ["oled:SDA", "pico:GP16", "blue", []],
        ["oled:SCL", "pico:GP17", "green", []],
        ["btn:1.l", "pico:GP26", "violet", []],
        ["btn:2.l", "pico:GND.7", "black", []],
    ]
    for i, (name, _, led) in enumerate(VL + US):
        parts.append({"type": "wokwi-led", "id": f"led{name}", "top": -60 + i * 40, "left": -120,
                      "attrs": {"color": "green", "label": name}})
        wires += [[f"led{name}:A", f"pico:GP{led}", "green", []],
                  [f"led{name}:C", f"pico:GND.{1 + i % 4}", "black", []]]
    for i, (name, trig, _) in enumerate(US):
        parts.append({"type": "wokwi-hc-sr04", "id": f"sonar{name}", "top": 260, "left": -100 + i * 160,
                      "attrs": {"distance": str(400 + i * 500)}})
        wires += [[f"sonar{name}:VCC", "pico:VBUS", "red", []],
                  [f"sonar{name}:GND", f"pico:GND.{3 + i % 4}", "black", []],
                  [f"sonar{name}:TRIG", f"pico:GP{trig}", "orange", []],
                  [f"sonar{name}:ECHO", f"pico:GP{trig + 1}", "cyan", []]]
    return json.dumps({"version": 1, "author": "NandoMadrid", "editor": "wokwi",
                       "parts": parts, "connections": wires, "dependencies": {}}, indent=2) + "\n"


def main():
    (HERE / "r2_pico_sensors.h").write_text(sketch(), encoding="utf-8", newline="\n")
    (HERE / "sketch.ino").write_text(f'{GENERATED}\n#define WOKWI 1\n#include "r2_pico_sensors.h"\n',
                                     encoding="utf-8", newline="\n")
    (HERE / "diagram.json").write_text(diagram(), encoding="utf-8", newline="\n")
    (HERE / "libraries.txt").write_text("Adafruit GFX Library\nAdafruit BusIO\nVL53L0X\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
