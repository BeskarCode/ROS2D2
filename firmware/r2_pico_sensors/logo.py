"""Write Logo.h: the Astromech Spain logo (r2_web/www/astromech-spain-logo.png) as a 128x20
1-bit bitmap for the display (Adafruit GFX drawBitmap format: rows, MSB first).

    python logo.py
"""
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PNG = os.path.join(HERE, "..", "..", "ros2_ws", "src", "r2_web", "www", "astromech-spain-logo.png")


def main():
    im = Image.open(PNG).convert("RGBA")
    w = 128
    h = round(im.height * w / im.width)
    im = im.resize((w, h), Image.LANCZOS)
    rows = []
    for y in range(h):
        for xb in range(0, w, 8):
            v = 0
            for k in range(8):
                r, g, b, a = im.getpixel((xb + k, y))
                if a > 110 and (r + g + b) / 3 > 60:
                    v |= 0x80 >> k
            rows.append(f"0x{v:02x}")
    lines = [", ".join(rows[i:i + 16]) for i in range(0, len(rows), 16)]
    with open(os.path.join(HERE, "Logo.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by logo.py from r2_web/www/astromech-spain-logo.png: do not edit.\n#pragma once\n\n"
                f"constexpr int LOGO_W = {w}, LOGO_H = {h};\n"
                "const unsigned char LOGO[] = {\n  " + ",\n  ".join(lines) + "\n};\n")
    print("Logo.h", w, "x", h)


if __name__ == "__main__":
    main()
